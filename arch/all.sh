#!/usr/bin/env bash

features=(
	base
	themes

	#---------------------------------------------------------
	# DE
	#---------------------------------------------------------
	# xfce
	# kde

	#---------------------------------------------------------
	# WM
	#---------------------------------------------------------
	# niri
	# hyprland
	wayfire


	#---------------------------------------------------------
	# Dev
	#---------------------------------------------------------
	dev
	nvim
	flutter

	#---------------------------------------------------------
	# Extras
	#---------------------------------------------------------
	monitoring
	office
)

for feature in "${features[@]}"; do
	echo "${feature} => install"

	if [ -f "${feature}.sh" ]; then
		bash "arch/${feature}.sh"
	else
		echo "warn => ${feature}.sh not found"
	fi

	echo "${features} => done"
done
